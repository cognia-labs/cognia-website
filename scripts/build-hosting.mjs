#!/usr/bin/env node
/** Generate host-specific redirects from the canonical origin baked into the static export. */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

export function canonicalOrigin(html) {
  const match =
    /<link\b(?=[^>]*\brel=["']canonical["'])(?=[^>]*\bhref=["']([^"']+)["'])[^>]*>/i.exec(html)
  if (!match) throw new Error("Missing canonical link in out/index.html")
  const url = new URL(match[1])
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password)
    throw new Error("Invalid canonical HTTP(S) origin")
  return url.origin
}
export function pagesRedirects(origin) {
  const url = new URL(origin)
  if (!["http:", "https:"].includes(url.protocol) || url.origin !== origin)
    throw new Error("Expected an HTTP(S) origin")
  // Absolute destinations keep any wildcard (including // or encoded slashes) on our canonical host.
  return `# Generated by scripts/build-hosting.mjs from the built canonical origin.\n/en ${origin}/ 301\n/en/* ${origin}/:splat 301\n`
}
if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const output = join(dirname(fileURLToPath(import.meta.url)), "../out")
  const origin = canonicalOrigin(readFileSync(join(output, "index.html"), "utf8"))
  writeFileSync(join(output, "_redirects"), pagesRedirects(origin))
  console.log(`[hosting] Pages redirects fixed to ${origin}`)
}
